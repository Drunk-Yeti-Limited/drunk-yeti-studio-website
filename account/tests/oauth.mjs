import assert from 'node:assert/strict';
import {GoTrueClient} from '@supabase/auth-js';
import {accountAuthOptions} from '../src/recovery.js';
import {providerSignInOptions,cleanAuthCallback} from '../src/oauth.js';

const callback='https://www.drunkyetistudio.com/account/';
const store=new Map();
const storage={getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value),removeItem:key=>store.delete(key)};
const requests=[];
const options={url:'https://auth.example.test',...accountAuthOptions(callback),autoRefreshToken:false,storage,storageKey:'oauth-test',fetch:async(url,options)=>{
  requests.push({url:String(url),body:options.body?JSON.parse(options.body):null});
  assert.match(String(url),/\/token\?grant_type=pkce$/);
  return new Response(JSON.stringify({access_token:'test-access',refresh_token:'test-refresh',expires_in:3600,token_type:'bearer',user:{id:'existing-player',email:'qa@example.invalid'}}),{status:200});
}};
const sender=new GoTrueClient(options);
await sender.initialize();
const credentials=providerSignInOptions('google',callback);
credentials.options.skipBrowserRedirect=true;
const started=await sender.signInWithOAuth(credentials);
assert.equal(started.error,null);
const authorize=new URL(started.data.url);
assert.equal(authorize.origin,'https://auth.example.test');
assert.equal(authorize.searchParams.get('provider'),'google');
assert.equal(authorize.searchParams.get('prompt'),'select_account');
assert.equal(authorize.searchParams.get('scopes'),'openid email profile');
assert.equal(authorize.searchParams.get('code_challenge_method'),'s256');
assert.ok(authorize.searchParams.get('code_challenge').length>30);
const returned=new URL(authorize.searchParams.get('redirect_to'));
assert.equal(returned.origin+returned.pathname,callback);
returned.searchParams.set('code','one-use-auth-code');
globalThis.window={location:returned,history:{state:null,replaceState(_state,_title,url){window.location=new URL(url)}}};
globalThis.document={visibilityState:'visible',addEventListener(){}};
globalThis.BroadcastChannel=undefined;
const events=[];
const receiver=new GoTrueClient({...options,...accountAuthOptions(returned.href),autoRefreshToken:false});
receiver.onAuthStateChange(event=>events.push(event));
assert.equal((await receiver.initialize()).error,null);
await new Promise(resolve=>setTimeout(resolve,20));
assert.equal(requests.length,1);
assert.equal(requests[0].body.auth_code,'one-use-auth-code');
assert.ok(requests[0].body.code_verifier.length>30);
assert.equal((await receiver.getSession()).data.session.user.id,'existing-player');
assert.ok(events.includes('SIGNED_IN'));
assert.ok(!events.includes('PASSWORD_RECOVERY'));
assert.equal(window.location.search,'');
assert.equal(cleanAuthCallback(callback+'?code=secret&membership=success#error=access_denied&error_description=private'),callback+'?membership=success');
assert.equal(cleanAuthCallback(callback+'#marketplace'),callback+'#marketplace');
assert.equal(cleanAuthCallback(callback+'#reset-password'),callback+'#reset-password');
assert.deepEqual(providerSignInOptions('apple',callback),{provider:'apple',options:{redirectTo:callback}});
await receiver.stopAutoRefresh();
await sender.stopAutoRefresh();
console.log('PASS real SDK Google PKCE challenge, minimal scopes, account chooser, code exchange, session persistence, SIGNED_IN event and callback cleanup (mocked HTTP)');
