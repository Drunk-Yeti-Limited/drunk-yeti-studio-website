import assert from 'node:assert/strict';
import {parseHTML} from 'linkedom';
import {GoTrueClient} from '@supabase/auth-js';
import {socialPlatforms,normalizeSocialHandle,socialURL,renderSocialLinks,renderSignInConnections} from '../src/social.js';
import {loginMethods} from '../sdk/account-client.js';
import {providerSignInOptions} from '../src/oauth.js';
import {accountAuthOptions} from '../src/recovery.js';
const {document}=parseHTML('<div id="root"></div>');globalThis.document=document;
const root=document.getElementById('root');
assert.equal(socialPlatforms.length,16);
assert.equal(normalizeSocialHandle('twitter',' @yeti '),'yeti');
for(const input of ['https://evil.test','javascript:alert(1)','../evil','<img src=x>', 'x'.repeat(65)])assert.throws(()=>normalizeSocialHandle('github',input));
assert.throws(()=>normalizeSocialHandle('unknown','test'));
assert.throws(()=>normalizeSocialHandle('nintendo','1234'));
assert.equal(socialURL('steam','76561198000000000'),'https://steamcommunity.com/profiles/76561198000000000');
assert.equal(socialURL('steam','yeti'),'https://steamcommunity.com/id/yeti');
assert.equal(socialURL('xbox','Yeti #1234'),null);
assert.equal(socialURL('nintendo','SW-1234-5678-9012'),null);
assert.equal(socialURL('discord','yeti'),null);
renderSocialLinks(root,[{platform:'twitter',handle:'<img src=x onerror=alert(1)>'}]);
assert.equal(root.querySelector('img'),null);assert.equal(root.querySelector('a'),null);assert.match(root.textContent,/Self-reported/);
renderSocialLinks(root,[{platform:'github',handle:'yeti'}]);assert.equal(root.querySelector('a').rel,'noopener noreferrer');
let disconnected,linked;
renderSignInConnections(root,[{id:'one',provider:'github'}],[{id:'github',name:'GitHub'},{id:'discord',name:'Discord'}],{canLink:true,link:id=>linked=id,unlink:i=>disconnected=i});
assert.equal(root.querySelector('button').disabled,true);root.querySelectorAll('button')[1].click();assert.equal(linked,'discord');assert.equal(disconnected,undefined);
renderSignInConnections(root,[],[{id:'discord',name:'Discord'}],{link(){},unlink(){}});assert.equal(root.querySelector('button').disabled,true);assert.match(root.textContent,/being prepared/);
const providers=['discord','github','x','twitch','azure','linkedin_oidc','gitlab'];
for(const provider of providers){
 const manifest={auth:{providers:[{id:provider,name:provider,ready_surfaces:['web']}]}};
 assert.equal(loginMethods(manifest,{external:{[provider]:true}}).length,1);
 assert.equal(loginMethods(manifest,{external:{[provider]:false}}).length,0);
 assert.equal(loginMethods(manifest,{external:{[provider]:true}},'ios').length,0);
 const sdk=new GoTrueClient({url:'https://auth.example.test',...accountAuthOptions('https://www.drunkyetistudio.com/account/'),persistSession:false,autoRefreshToken:false});
 await sdk.initialize();const params=providerSignInOptions(provider,'https://www.drunkyetistudio.com/account/');params.options.skipBrowserRedirect=true;
 const {data,error}=await sdk.signInWithOAuth(params);assert.equal(error,null);const url=new URL(data.url);
 assert.equal(url.searchParams.get('provider'),provider);assert.equal(url.searchParams.get('code_challenge_method'),'s256');assert.ok(url.searchParams.get('code_challenge'));
 if(provider==='azure')assert.equal(url.searchParams.get('scopes'),'email');
 await sdk.stopAutoRefresh();
}
